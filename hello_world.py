#!/usr/bin/env python3
"""
A simple script that prints a hello world message from a multi-agent team.
"""

def get_message():
    """Returns the hello world message."""
    return "hello world from multi-agent team!"

def main():
    """Main function that prints the hello world message."""
    message = get_message()
    print(message)

if __name__ == "__main__":
    main()
